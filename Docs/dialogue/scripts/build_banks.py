"""Build the dialogue banks from drafts/, one bank per voice and chat-range tier, and point each behavior at its bank.

drafts/<Category>-<FACTION>.txt holds every line of one voice:
    voice: GAALSIEN            (optional; picks the red GAALSIEN chat profiles, else the white ones)
    ## TargetAcquired
    One line per row. Blank lines and lines starting with # are ignored.
    [S], [M] or [L] at the start of a line (or a mix like [ML]) limits it to the Small, Medium or Large bank,
    so a Sandskimmer and a Cruiser of the same faction share a voice but can say different things.

Chat range comes from the behavior's Encounter Type (see TIER), so one voice can produce up to three banks:
    Content/Data/DialogueBanks/GVK-<Category>-<FACTION>-<Small|Medium|Large>.xml
Each behavior's [DialogueBanks:] line is rewritten to the bank for its faction voice and tier.

Usage (from Docs/dialogue):
    python scripts/build_banks.py            build banks and rewire behaviors
    python scripts/build_banks.py --check    report only, change nothing (exit 1 if anything is out of date)
    python scripts/build_banks.py --import   one-off: seed drafts/ from the existing bank XML files
"""
import glob, io, os, re, sys
from xml.sax.saxutils import escape

HERE = os.path.dirname(os.path.abspath(__file__))
DOCS = os.path.normpath(os.path.join(HERE, ".."))
REPO = os.path.normpath(os.path.join(DOCS, "..", ".."))
DATA = os.path.join(REPO, "Content", "Data")
BANKS = os.path.join(DATA, "DialogueBanks")
DRAFTS = os.path.join(DOCS, "drafts")
AUDIO = "ArcHudGPSNotification2"

# Chat range tier per Encounter Type. Ranges live on the chat profiles GVK-Universal-Chat-Voice[-GAALSIEN]-<Tier>
# (Small 5 km, Medium 15 km, Large server-wide) in GVK-Universal-Behavior.sbc.
TIER = {
    "DroneSmall": "Small", "WreckSmall": "Small", "AllianceTurret": "Small",
    "DroneMedium": "Medium", "WreckMedium": "Medium", "CargoShip": "Medium", "AllianceOutpost": "Medium",
    "DroneLarge": "Large", "DroneElite": "Large", "WreckLarge": "Large", "AllianceBase": "Large",
}
# Rare or unique encounters whose Encounter Type undersells them.
TIER_OVERRIDE = {
    "GVK-PlanetaryInstallation-Small-Behavior-COALITIONTurretPost": "Medium",
    "GVK-PlanetaryInstallation-Small-Behavior-COALITIONRelay": "Medium",
    "GVK-Other-Recovery-Behavior-COALITION": "Large",
    "GVK-Convoy-GAALSIENCarrier-Lead-Behavior": "Large",
    "GVK-Convoy-GAALSIENSmallConvoy-Lead-Behavior": "Large",
}
SIZE = {"S": "Small", "M": "Medium", "L": "Large"}
BANK_RE = re.compile(r"^GVK-(Units|Travellers|Structures|Installations)-([A-Z]+)(?:-(Small|Medium|Large))?\.xml$")


def read(p):
    return io.open(p, encoding="utf-8", newline="").read()


def write(p, text):
    io.open(p, "w", encoding="utf-8", newline="").write(text)


def load_profiles():
    profiles, files = {}, {}
    for f in glob.glob(os.path.join(DATA, "**", "*.sbc"), recursive=True):
        if os.sep + "Prefabs" + os.sep in f:
            continue
        for m in re.finditer(r"<SubtypeId>([^<]+)</SubtypeId>\s*</Id>\s*<Description>(.*?)</Description>", read(f), re.S):
            profiles[m.group(1).strip()] = m.group(2)
            files[m.group(1).strip()] = f
    return profiles, files


def tags(desc, name):
    return [v.strip() for v in re.findall(r"\[" + name + r":([^\]]+)\]", desc)]


def encounter_type(behavior, profiles):
    """Follow the behavior's triggers (direct and in trigger groups) to the action that sets EncounterType."""
    desc = profiles[behavior]
    triggers = tags(desc, "Triggers")
    for g in tags(desc, "TriggerGroups"):
        triggers += tags(profiles.get(g, ""), "Triggers")
    found = set()
    for t in triggers:
        tdesc = profiles.get(t, "")
        for a in tags(tdesc, "Actions") + tags(tdesc, "ElseActions"):
            found.update(re.findall(r"\[CustomStrings:EncounterType,([^\]]+)\]", profiles.get(a, "")))
    return found


def parse_draft(path):
    voice, cues, cur = "", {}, None
    for raw in read(path).splitlines():
        line = raw.strip()
        if not line or line.startswith("#") and not line.startswith("##"):
            continue
        if line.lower().startswith("voice:"):
            voice = line.split(":", 1)[1].strip()
        elif line.startswith("##"):
            cur = line[2:].strip()
            cues.setdefault(cur, [])
        elif cur:
            m = re.match(r"\[([SML]+)\]\s*(.*)", line)
            only = {SIZE[c] for c in m.group(1)} if m else None
            cues[cur].append((only, m.group(2) if m else line))
    return voice, cues


def render(name, voice, cues, tier):
    chat = f"GVK-Universal-Chat-Voice{'-GAALSIEN' if voice == 'GAALSIEN' else ''}-{tier}"
    out = ['<?xml version="1.0" encoding="utf-8"?>',
           f"<!-- GENERATED by Docs/dialogue/scripts/build_banks.py from Docs/dialogue/drafts/{name}.txt. Edit the draft, not this file. -->",
           "<DialogueBank>", f"\t<ChatProfileId>{chat}</ChatProfileId>"]
    for cue, entries in cues.items():
        msgs = [text for only, text in entries if only is None or tier in only]
        if not msgs:
            continue
        out += ["\t<DialogueCue>", f"\t\t<DialogueCueId>{cue}</DialogueCueId>", "\t\t<Entries>"]
        for m in msgs:
            out += ["\t\t\t<Entry>", f"\t\t\t\t<Message>{escape(m)}</Message>", f"\t\t\t\t<AudioId>{AUDIO}</AudioId>",
                    "\t\t\t\t<Weights>1</Weights>", "\t\t\t</Entry>"]
        out += ["\t\t</Entries>", "\t</DialogueCue>"]
    out.append("</DialogueBank>")
    return "\r\n".join(out) + "\r\n"


def import_banks():
    os.makedirs(DRAFTS, exist_ok=True)
    for p in sorted(glob.glob(os.path.join(BANKS, "*.xml"))):
        m = BANK_RE.match(os.path.basename(p))
        if not m or m.group(3):
            continue
        name = f"{m.group(1)}-{m.group(2)}"
        t = read(p)
        voice = "GAALSIEN" if "UnitVoice-GAALSIEN" in t else ""
        lines = [f"# {name}: original lines. Write new ones under each cue.", f"voice: {voice}" if voice else ""]
        for cue in re.finditer(r"<DialogueCueId>([^<]+)</DialogueCueId>(.*?)</DialogueCue>", t, re.S):
            lines += ["", f"## {cue.group(1)}"]
            lines += [re.sub(r"&apos;", "'", x) for x in re.findall(r"<Message>([^<]*)</Message>", cue.group(2))]
        out = os.path.join(DRAFTS, name + ".txt")
        if os.path.exists(out):
            print("skip existing", out)
            continue
        write(out, "\r\n".join(l for l in lines if l is not None) + "\r\n")
        print("seeded", os.path.relpath(out, DOCS))


def build(check):
    profiles, files = load_profiles()
    problems, wanted, rewires = [], {}, {}
    for b, desc in sorted(profiles.items()):
        if "[RivalAI Behavior]" not in desc:
            continue
        banks = tags(desc, "DialogueBanks")
        if not banks:
            continue
        m = BANK_RE.match(banks[0])
        if not m:
            problems.append(f"{b}: bank {banks[0]} is not GVK-<Category>-<FACTION>[-<Tier>].xml")
            continue
        voice = f"{m.group(1)}-{m.group(2)}"
        copy_of = tags(desc, "//CopyOf")
        source = copy_of[0] if copy_of else b
        tier = TIER_OVERRIDE.get(source)
        if not tier:
            types = encounter_type(source, profiles)
            tiers = {TIER.get(t) for t in types}
            if len(tiers) != 1 or None in tiers:
                problems.append(f"{b}: can't pick a tier from Encounter Type {sorted(types) or 'none'}; add it to TIER_OVERRIDE")
                continue
            tier = tiers.pop()
        wanted.setdefault(voice, set()).add(tier)
        target = f"GVK-{voice}-{tier}.xml"
        if banks[0] != target:
            rewires[b] = (banks[0], target)

    drafts = {os.path.splitext(os.path.basename(p))[0]: p for p in glob.glob(os.path.join(DRAFTS, "*.txt"))}
    outputs = {}
    for voice, tiers in sorted(wanted.items()):
        if voice not in drafts:
            problems.append(f"no draft for {voice} (expected drafts/{voice}.txt)")
            continue
        v, cues = parse_draft(drafts[voice])
        for tier in sorted(tiers):
            outputs[f"GVK-{voice}-{tier}.xml"] = render(voice, v, cues, tier)

    changed = []
    for name, text in outputs.items():
        p = os.path.join(BANKS, name)
        if not os.path.exists(p) or read(p) != text:
            changed.append(f"bank {name}")
            if not check:
                write(p, text)
    for p in glob.glob(os.path.join(BANKS, "*.xml")):
        if os.path.basename(p) not in outputs:
            changed.append(f"remove stale bank {os.path.basename(p)}")
            if not check:
                os.remove(p)
    for b, (old, new) in sorted(rewires.items()):
        changed.append(f"{b}: {old} -> {new}")
        if not check:
            # Replace inside this behavior's own Description: a file can hold behaviors of different tiers.
            f = files[b]
            text = read(f)
            m = re.search(r"<SubtypeId>" + re.escape(b) + r"</SubtypeId>\s*</Id>\s*<Description>.*?</Description>", text, re.S)
            block = m.group(0).replace(f"[DialogueBanks:{old}]", f"[DialogueBanks:{new}]")
            write(f, text[:m.start()] + block + text[m.end():])

    for p in problems:
        print("PROBLEM:", p)
    for c in changed:
        print(("WOULD " if check else "") + c)
    if not changed and not problems:
        print("Dialogue banks up to date.")
    return 1 if problems or (check and changed) else 0


if __name__ == "__main__":
    if "--import" in sys.argv:
        import_banks()
        sys.exit(0)
    sys.exit(build("--check" in sys.argv))
